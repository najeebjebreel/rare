"""Generate the target-model performance appendix table (tab:model-performance).

Reads each target's ``model_<t>/metrics.csv`` (Best_epoch, Train_loss,
Test_loss, Train_acc, Test_acc), written by the training pipeline's
final-epoch evaluation, and reports mean +/- std over the ten targets per
benchmark: cross-entropy loss and accuracy on the target's own training
members (no augmentation) and on the held-out test set.

Outputs paper_tabs_figs/tables/tab_model_performance.{tex,csv}.

Usage:
  python paper_tabs_figs/tab_model_performance.py
"""

from __future__ import annotations

import argparse
import csv as _csv
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]

BENCHMARKS = {
    "CIFAR10": ROOT / "experiments/cifar10/wrn28-2/2025-12-07_0140",
    "CIFAR100": ROOT / "experiments/cifar100/wrn28-2/2025-12-25_0121",
    "CINIC10": ROOT / "experiments/cinic10/wrn28-2/2026-05-11_0215",
}
TARGETS = [0, 25, 50, 75, 100, 125, 150, 175, 200, 250]
# (metrics.csv column, output key, unit)
FIELDS = [
    ("Train_loss", "train_loss"),
    ("Test_loss", "test_loss"),
    ("Train_acc (%)", "train_acc"),
    ("Test_acc (%)", "test_acc"),
]
DEFAULT_OUT = ROOT / "paper_tabs_figs/tables"


def _read_metrics(exp: Path):
    """Return {key: array over targets} from the per-target metrics.csv."""
    cols = {k: [] for _, k in FIELDS}
    for t in TARGETS:
        p = exp / f"model_{t}" / "metrics.csv"
        if not p.exists():
            raise FileNotFoundError(f"missing {p}; run the training final-eval first")
        with p.open() as f:
            row = next(iter(_csv.DictReader(f)))
        for src, key in FIELDS:
            cols[key].append(float(row[src]))
    return {k: np.asarray(v, dtype=np.float64) for k, v in cols.items()}


def collect():
    return {ds: _read_metrics(exp) for ds, exp in BENCHMARKS.items()}


def _fmt(mean: float, std: float, decimals: int) -> str:
    return f"{mean:.{decimals}f}{{\\scriptsize$\\pm${std:.{decimals}f}}}"


def write_outputs(stats, out_dir: Path):
    out_dir.mkdir(parents=True, exist_ok=True)

    # ---- CSV (long) ----
    with (out_dir / "tab_model_performance.csv").open("w", newline="") as f:
        w = _csv.writer(f)
        w.writerow(["dataset", "metric", "mean", "std"])
        for ds in BENCHMARKS:
            for _, key in FIELDS:
                a = stats[ds][key]
                w.writerow([ds, key, f"{a.mean():.4f}", f"{a.std(ddof=1):.4f}"])

    # ---- LaTeX ----
    lines = [
        "% Auto-generated by paper_tabs_figs/tab_model_performance.py -- do not edit by hand.",
        r"""\begin{table}[t]
\centering
\caption{Target-model performance (WRN-28-2). Mean$\pm$std over the ten
targets per benchmark: cross-entropy loss and accuracy on the target's
own training members (no augmentation) and on the held-out test set.}
\label{tab:model-performance}
\footnotesize
\setlength{\tabcolsep}{5pt}
\renewcommand{\arraystretch}{1.05}""",
        "\\begin{tabular}{l cc cc}",
        "\\toprule",
        "\\multirow{2}{*}{\\textbf{Dataset}}"
        " & \\multicolumn{2}{c}{\\textbf{Loss}}"
        " & \\multicolumn{2}{c}{\\textbf{Accuracy (\\%)}} \\\\",
        "\\cmidrule(lr){2-3} \\cmidrule(lr){4-5}",
        " & \\textbf{Train} & \\textbf{Test} & \\textbf{Train} & \\textbf{Test} \\\\",
        "\\midrule",
    ]
    for ds in BENCHMARKS:
        s = stats[ds]
        cells = [
            _fmt(s["train_loss"].mean(), s["train_loss"].std(ddof=1), 4),
            _fmt(s["test_loss"].mean(), s["test_loss"].std(ddof=1), 3),
            _fmt(s["train_acc"].mean(), s["train_acc"].std(ddof=1), 2),
            _fmt(s["test_acc"].mean(), s["test_acc"].std(ddof=1), 2),
        ]
        lines.append(f"{ds} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (out_dir / "tab_model_performance.tex").write_text("\n".join(lines) + "\n")


def print_markdown(stats):
    print("| Dataset | Train loss | Test loss | Train acc (%) | Test acc (%) |")
    print("|---|---|---|---|---|")
    for ds in BENCHMARKS:
        s = stats[ds]
        print(f"| {ds} "
              f"| {s['train_loss'].mean():.4f}±{s['train_loss'].std(ddof=1):.4f} "
              f"| {s['test_loss'].mean():.3f}±{s['test_loss'].std(ddof=1):.3f} "
              f"| {s['train_acc'].mean():.2f}±{s['train_acc'].std(ddof=1):.2f} "
              f"| {s['test_acc'].mean():.2f}±{s['test_acc'].std(ddof=1):.2f} |")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()
    stats = collect()
    write_outputs(stats, args.out_dir)
    print_markdown(stats)
    print(f"\nwrote {args.out_dir / 'tab_model_performance.tex'}")
    print(f"wrote {args.out_dir / 'tab_model_performance.csv'}")


if __name__ == "__main__":
    main()
