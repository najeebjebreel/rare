"""Generate the component-contribution ablation LaTeX table (tab:abl-components).

Rows: reference-side LT-BTM-R alone, target-side LT-IQR alone, and the
locked member-normalized z-score sum (= RARE, M=1, q=50%). Cells are
capped Precision @ k in {1, 3, 5, 10}% under LiRA-256 gold at the FPR
threshold, mean +/- std over the 10 targets per dataset; the Avg column
is the mean +/- std over the three dataset means. Best per column bold,
second best underlined.

The standalone components are evaluated on their raw scores -- ranking
metrics are invariant to the monotone member-z-scoring, so z_M only
matters for the sum.

Usage:
  python paper_tabs_figs/tab_abl_components.py
  python paper_tabs_figs/tab_abl_components.py --fpr 1e-3 --q 0.5
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
for p in (str(ROOT), str(ROOT / "scripts")):
    if p not in sys.path:
        sys.path.insert(0, p)

from rare.analysis.utils import score_avg_min_q_reference_losses  # noqa: E402

_spec = importlib.util.spec_from_file_location(
    "main_table_mod", ROOT / "scripts" / "main_table.py")
_mt = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_mt)

BENCHMARKS = {
    "CIFAR10": ROOT / "experiments/cifar10/wrn28-2/2025-12-07_0140",
    "CIFAR100": ROOT / "experiments/cifar100/wrn28-2/2025-12-25_0121",
    "CINIC10": ROOT / "experiments/cinic10/wrn28-2/2026-05-11_0215",
}
DEFAULT_TARGETS = [0, 25, 50, 75, 100, 125, 150, 175, 200, 250]
DEFAULT_OUTPUT = ROOT / "paper_tabs_figs/figures/tab_abl_components.tex"
K_FRACS = [0.01, 0.03, 0.05, 0.10]


def _load_lt_btm_r(exp: Path, t: int, q: float) -> np.ndarray:
    target_dir = exp / f"model_{int(t)}"
    matches = sorted(target_dir.glob("ref_losses_E*_*_ref0.npy"))
    if not matches:
        raise FileNotFoundError(f"No ref_losses_E*_*_ref0.npy in {target_dir}")
    return score_avg_min_q_reference_losses(
        [np.load(matches[0]).astype(np.float32)], q=q)


def methods(q: float):
    return [
        ("LT-BTM-R alone", lambda exp, t: _load_lt_btm_r(exp, t, q)),
        ("LT-IQR alone", lambda exp, t: _mt._load_lt_iqr(exp, t)),
        ("$z_M(\\mathrm{LT\\mbox{-}BTM\\mbox{-}R})+z_M(\\mathrm{LT\\mbox{-}IQR})$",
         lambda exp, t: _mt._load_rare(exp, t, 1)),
    ]


def precision_at_k(exp: Path, targets, loader, fpr: float) -> np.ndarray:
    out = []
    for t in targets:
        gold_scores, members, vulnerable = _mt._load_lira_gold(exp, t, fpr)
        pr = _mt.tail_metrics_at_k(
            loader(exp, t), members, K_FRACS,
            vulnerable=vulnerable, gold_scores=gold_scores,
        )
        out.append([float(pr.iloc[i]["precision"]) for i in range(len(K_FRACS))])
    return np.asarray(out)


def _rank_decorations(col_means):
    order = np.argsort(-np.asarray(col_means))
    deco = {int(order[0]): "textbf"}
    if len(order) > 1:
        deco[int(order[1])] = "underline"
    return deco


def _fmt(mean, std, deco):
    body = f"{mean:.2f}"
    if deco:
        body = f"\\{deco}{{{body}}}"
    return f"{body}{{\\scriptsize$\\pm${std:.2f}}}"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--fpr", type=float, default=1e-4)
    ap.add_argument("--q", type=float, default=0.50)
    ap.add_argument("--targets", type=int, nargs="*", default=DEFAULT_TARGETS)
    ap.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = ap.parse_args()

    rows = methods(args.q)
    ds_names = list(BENCHMARKS)
    nk = len(K_FRACS)
    n_cols = (len(ds_names) + 1) * nk
    cell_mean = np.zeros((len(rows), n_cols))
    cell_std = np.zeros_like(cell_mean)
    for mi, (_, loader) in enumerate(rows):
        ds_means = []
        for di, name in enumerate(ds_names):
            pk = precision_at_k(BENCHMARKS[name], args.targets, loader, args.fpr)
            cell_mean[mi, di * nk:(di + 1) * nk] = pk.mean(axis=0)
            cell_std[mi, di * nk:(di + 1) * nk] = pk.std(axis=0, ddof=1)
            ds_means.append(pk.mean(axis=0))
        ds_means = np.asarray(ds_means)
        cell_mean[mi, -nk:] = ds_means.mean(axis=0)
        cell_std[mi, -nk:] = ds_means.std(axis=0, ddof=1)

    col_deco = [_rank_decorations(cell_mean[:, c]) for c in range(n_cols)]

    q_pct = int(round(args.q * 100))
    header_ks = " ".join(
        "& \\textbf{P@1\\%} & \\textbf{P@3\\%} & \\textbf{P@5\\%} & \\textbf{P@10\\%}"
        for _ in range(4))
    lines = [
        "% Auto-generated by paper_tabs_figs/tab_abl_components.py -- do not edit by hand.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Component contribution: reference-side LT-BTM-R, target-side"
        " LT-IQR, and their member-normalized z-score sum. LT-BTM-R uses"
        f" $q={q_pct}\\%$.}}",
        "\\label{tab:abl-components}",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\renewcommand{\\arraystretch}{1.05}",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{l cccc cccc cccc cccc}",
        "\\toprule",
        "\\multirow{2}{*}{\\textbf{Score}}",
    ]
    for name in ds_names + ["Avg."]:
        lines.append(f"  & \\multicolumn{{4}}{{c}}{{\\textbf{{{name}}}}}")
    lines += [
        "\\\\",
        "\\cmidrule(lr){2-5} \\cmidrule(lr){6-9} \\cmidrule(lr){10-13}"
        " \\cmidrule(lr){14-17}",
        " " + header_ks + " \\\\",
        "\\midrule",
    ]
    for mi, (label, _) in enumerate(rows):
        cells = [label]
        for c in range(n_cols):
            cells.append(_fmt(cell_mean[mi, c], cell_std[mi, c],
                              col_deco[c].get(mi)))
        block = [cells[0]]
        for di in range(4):
            block.append("& " + " & ".join(cells[1 + di * nk:1 + (di + 1) * nk]))
        lines.append("\n".join(block) + " \\\\")
        lines.append("")
    lines += ["\\bottomrule", "\\end{tabular}}", "\\end{table*}"]

    tex = "\n".join(lines)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(tex + "\n")
    print(tex)

    print("\n% ---- prose numbers ----")
    labels = [r[0] for r in rows]
    for j, k in enumerate(["P@1%", "P@3%", "P@5%", "P@10%"]):
        vals = " | ".join(f"{labels[i][:12]:>12} {cell_mean[i, -nk + j]:.2f}"
                          for i in range(len(rows)))
        print(f"% Avg {k}: {vals}")
    # Per-dataset sum-vs-best-component gain at each k.
    gains = cell_mean[2] - np.maximum(cell_mean[0], cell_mean[1])
    print(f"% sum - best component, min/max over all dataset x k cells: "
          f"{gains[:12].min() * 100:+.1f} / {gains[:12].max() * 100:+.1f} pp")


if __name__ == "__main__":
    main()
