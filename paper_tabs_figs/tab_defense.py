"""Generate the RARE-guided mitigation LaTeX table (tab:defense).

Locked defense: serve, for every member, the blended logits
(1-a)*target + a*ref0 with a = sigmoid(RARE / tau), tau=2 (reuses the OUT
reference RARE already trains; test queries untouched). For each benchmark
and SotA attack we report before/after Train Acc, Test Acc, MIA AUC, and
MIA TPR@FPR in {1e-3, 1e-4, 1e-5}, plus the per-target defense runtime
overhead.

Sources, all reproducible:
  - MIA AUC/TPR + member (train) accuracy: scripts/defense_eval.evaluate_benchmark
    at tau=2 (reads cached ref_logits_*.npy; sanity gate must be ~0).
  - Test accuracy (unchanged by the defense): <exp>/model_<t>/metrics.csv.
  - Runtime overhead: one A=2 reference forward to cache ref logits
    (<exp>/logit_gen_runtime.csv, num_augs=2); the per-query blend is O(C),
    negligible. This is the only compute on top of the RARE pipeline.

Usage:
  python paper_tabs_figs/tab_defense.py            # runs tau=2 on all 3 benchmarks
"""

from __future__ import annotations

import argparse
import csv
import importlib.util
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
for p in (str(ROOT), str(ROOT / "scripts")):
    if p not in sys.path:
        sys.path.insert(0, p)

_spec = importlib.util.spec_from_file_location("de", ROOT / "scripts" / "defense_eval.py")
de = importlib.util.module_from_spec(_spec); _spec.loader.exec_module(de)

import tab_pipeline_cost as tpc  # noqa: E402  (RARE per-target pipeline cost)

DEFAULT_OUTPUT = ROOT / "paper_tabs_figs/tables/tab_defense.tex"
TARGETS = de.TARGETS
TAU = 2.0
DISPLAY = {"cifar10": "CIFAR-10", "cifar100": "CIFAR-100", "cinic10": "CINIC-10"}
ATTACK_TEX = {"LiRA-256": "LiRA-256", "RMIA-256": "RMIA-256",
              "Attack-R-128": "Attack-R-128"}


def _mean_metrics_csv(exp: Path, col: str) -> tuple[float, float]:
    vals = []
    for t in TARGETS:
        rows = list(csv.DictReader(open(exp / f"model_{t}" / "metrics.csv")))
        vals.append(float(rows[-1][col]))
    v = np.asarray(vals)
    return float(v.mean()), float(v.std(ddof=1))


_TPC_KEY = {"cifar10": "CIFAR10", "cifar100": "CIFAR100", "cinic10": "CINIC10"}


def _rare_total_sec(name: str) -> float:
    """RARE (M=1) per-target pipeline total from the runtime logs (the same
    number reported in tab:pipeline-cost). The reference and its logits are
    produced here, so this already includes the defense's logit generation."""
    rows = tpc.build_rows(tpc.collect(tpc.DEFAULT_BENCHMARKS[_TPC_KEY[name]]))
    return rows["RARE (M=1)"][3].mean


def _blend_sec(num_classes: int, n_members: int = 25000, reps: int = 20) -> float:
    """Per-target blend cost: (1-a)*target + a*ref over the member logits
    (A=2). O(N*C); measured on representative sizes, CPU."""
    import time
    a = np.random.rand(n_members, 1, 1).astype(np.float32)
    t = np.random.rand(n_members, 2, num_classes).astype(np.float32)
    r = np.random.rand(n_members, 2, num_classes).astype(np.float32)
    best = float("inf")
    for _ in range(reps):
        t0 = time.perf_counter()
        _ = (1 - a) * t + a * r
        best = min(best, time.perf_counter() - t0)
    return best


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = ap.parse_args()

    lines = [
        "% Auto-generated by paper_tabs_figs/tab_defense.py -- do not edit by hand.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{RARE-guided mitigation (\\textbf{locked}: per-member served"
        " logits $(1{-}\\alpha)\\ell^{T}+\\alpha\\ell^{R}$, $\\alpha=\\sigma(\\mathrm{RARE}/\\tau)$,"
        " $\\tau{=}2$, applied to all members; test queries untouched). Before"
        " $\\to$ after the defense. Train Acc is over members; Test Acc is"
        " unchanged by construction. Runtime is the per-target"
        " identify-and-protect cost \\emph{on top of an already-trained"
        " target}: the RARE pipeline (Table~\\ref{tab:pipeline-cost}) --"
        " reference retrain plus the target's trace overhead -- and the"
        " per-member blend. Training the target itself is excluded, as is"
        " the case for every method in Table~\\ref{tab:pipeline-cost}. The"
        " reference and its logits are produced within RARE; the blend is"
        " $O(C)$ and negligible.}",
        "\\label{tab:defense}",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\renewcommand{\\arraystretch}{1.05}",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{l l cc cc cc cc cc c}",
        "\\toprule",
        "\\multirow{2}{*}{\\textbf{Data}} & \\multirow{2}{*}{\\textbf{Attack}}"
        " & \\multicolumn{2}{c}{\\textbf{Train Acc}}"
        " & \\multicolumn{2}{c}{\\textbf{Test Acc}}"
        " & \\multicolumn{2}{c}{\\textbf{AUC}}"
        " & \\multicolumn{2}{c}{\\textbf{TPR@$10^{-3}$}}"
        " & \\multicolumn{2}{c}{\\textbf{TPR@$10^{-4}$}}"
        " & \\textbf{Runtime} \\\\",
        "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\\cmidrule(lr){7-8}"
        "\\cmidrule(lr){9-10}\\cmidrule(lr){11-12}",
        " & & before & after & before & after & before & after"
        " & before & after & before & after & (s/target) \\\\",
        "\\midrule",
    ]
    # Note: TPR@1e-5 reported in the running text; kept out of the table to fit.

    prose = []
    tpr4_after_per_target = {}
    n_members = {}
    for name in de.BENCHMARKS:
        exp = de.BENCHMARKS[name]
        agg, util, sanity = de.evaluate_benchmark(name, exp, [TAU], TARGETS)
        max_sanity = max(max(s.values()) for s in sanity)
        if max_sanity > 1e-3:
            # Hard failure: the undefended pipeline must reproduce the cached
            # attack signals exactly, or every before/after number in this
            # table is meaningless. Never write a table past this point.
            worst = max(((v, at) for s in sanity for at, v in s.items()))
            raise SystemExit(
                f"SANITY GATE FAILED for {name}: max|Δsignal| = {max_sanity:.2e} "
                f"(tolerance 1e-3), worst attack = {worst[1]}. The recomputed "
                f"attack signal does not match <exp>/signals/*.npy, so the "
                f"defended numbers cannot be trusted. Nothing was written."
            )
        tr_b = np.mean([u[0] for u in util[TAU]]) * 100
        tr_a = np.mean([u[1] for u in util[TAU]]) * 100
        te_m, _ = _mean_metrics_csv(exp, "Test_acc (%)")
        _keep = np.load(exp / "keep_indices.npy").astype(bool)
        n_members[name] = [int(_keep[t].sum()) for t in TARGETS]
        import yaml as _yaml
        ncls = int(_yaml.safe_load(open(exp / "logit_config.yaml"))["dataset"]["num_classes"])
        runtime = _rare_total_sec(name) + _blend_sec(ncls)   # RARE total + blend
        attacks = list(de.SIG_FN)
        for ai, at in enumerate(attacks):
            b = np.array(agg[TAU][at]["base"]); d = np.array(agg[TAU][at]["def"])
            auc_b, auc_a = b[:, 0].mean(), d[:, 0].mean()
            t3b, t3a = b[:, 1].mean(), d[:, 1].mean()
            t4b, t4a = b[:, 2].mean(), d[:, 2].mean()
            t5b, t5a = b[:, 3].mean(), d[:, 3].mean()
            tpr4_after_per_target[(name, at)] = d[:, 2].copy()
            if ai == 0:
                head = (f"\\multirow{{3}}{{*}}{{{DISPLAY[name]}}}"
                        f" & {ATTACK_TEX[at]}"
                        f" & \\multirow{{3}}{{*}}{{{tr_b:.1f}}}"
                        f" & \\multirow{{3}}{{*}}{{{tr_a:.1f}}}"
                        f" & \\multirow{{3}}{{*}}{{{te_m:.1f}}}"
                        f" & \\multirow{{3}}{{*}}{{{te_m:.1f}}}")
                tail = f" & \\multirow{{3}}{{*}}{{{runtime:.0f}}}"
            else:
                head = f" & {ATTACK_TEX[at]} & & & & "
                tail = " & "
            lines.append(
                f"{head} & {auc_b:.2f} & {auc_a:.2f}"
                f" & {t3b:.4f} & {t3a:.4f} & {t4b:.4f} & {t4a:.4f}{tail} \\\\")
            prose.append((name, at, t5b, t5a))
        lines.append("\\midrule")
    lines[-1] = "\\bottomrule"
    lines += ["\\end{tabular}}", "\\end{table*}"]

    tex = "\n".join(lines)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(tex + "\n")
    print(tex)
    print("\n% ---- TPR@1e-5 (before -> after), for the running text ----")
    for name, at, b5, a5 in prose:
        print(f"% {name} {at}: {b5:.4f} -> {a5:.4f}")

    print("\n% ---- post-blend TPR@1e-4, FULL PRECISION (does anything survive?) ----")
    for at in ATTACK_TEX:
        print(f"% {at}")
        for name in de.BENCHMARKS:
            v = tpr4_after_per_target[(name, at)]
            nm = np.asarray(n_members[name], dtype=float)
            tp = v * nm                      # implied true positives per target
            nz = int((v > 0).sum())
            print(f"%   {name:<9} mean={v.mean():.10g}  max={v.max():.10g}  "
                  f"targets with TPR>0: {nz}/{len(v)}  implied TP total={tp.sum():.4g}")
            if nz:
                print(f"%     per-target TPR: "
                      + ", ".join(f"{x:.6g}" for x in v))


if __name__ == "__main__":
    main()
