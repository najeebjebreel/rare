"""Generate the reference-budget ablation LaTeX table (tab:abl-refM).

Sweeps M in {1, 2, 4, 8} for the locked RARE score (q=50%) on CIFAR-10.
Cells are Precision @ k in {1, 3, 5}% under LiRA-256 gold at the FPR
threshold, over a retrieval budget of ceil(k% * n_members), mean +/- std
over the 10 targets. Best per column bold, second best underlined.

Displayed at three decimals: the M=1 -> M=2 step is not a round 1 pp and
a two-decimal table hides that.

Usage:
  python paper_tabs_figs/tab_abl_refM.py
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
for p in (str(ROOT), str(ROOT / "scripts")):
    if p not in sys.path:
        sys.path.insert(0, p)

_spec = importlib.util.spec_from_file_location(
    "main_table_mod", ROOT / "scripts" / "main_table.py")
_mt = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_mt)

DEFAULT_EXP = ROOT / "experiments/cifar10/wrn28-2/2025-12-07_0140"
DEFAULT_TARGETS = [0, 25, 50, 75, 100, 125, 150, 175, 200, 250]
DEFAULT_OUTPUT = ROOT / "paper_tabs_figs/tables/tab_abl_refM.tex"
K_FRACS = [0.01, 0.03, 0.05]
M_LIST = [1, 2, 4, 8]


def _rank_decorations(col):
    order = np.argsort(-np.asarray(col))
    return {int(order[0]): "mathbf", int(order[1]): "underline"}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--experiment-dir", type=Path, default=DEFAULT_EXP)
    ap.add_argument("--fpr", type=float, default=1e-4)
    ap.add_argument("--q", type=float, default=0.50)
    ap.add_argument("--targets", type=int, nargs="*", default=DEFAULT_TARGETS)
    ap.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = ap.parse_args()
    exp = args.experiment_dir

    cell_mean = np.zeros((len(M_LIST), len(K_FRACS)))
    cell_std = np.zeros_like(cell_mean)
    for mi, m in enumerate(M_LIST):
        pks = []
        for t in args.targets:
            gold_scores, members, vulnerable = _mt._load_lira_gold(exp, t, args.fpr)
            scores = _mt.load_rare_locked_scores(exp, t, num_refs=m, q=args.q)
            pr = _mt.tail_metrics_at_k(
                scores, members, K_FRACS,
                vulnerable=vulnerable, gold_scores=gold_scores,
                cap_k_at_gold=False, k_rounding="ceil",
            )
            pks.append([float(pr.iloc[i]["precision"])
                        for i in range(len(K_FRACS))])
        pks = np.asarray(pks)
        cell_mean[mi] = pks.mean(axis=0)
        cell_std[mi] = pks.std(axis=0, ddof=1)

    col_deco = [_rank_decorations(cell_mean[:, j]) for j in range(len(K_FRACS))]

    q_pct = int(round(args.q * 100))
    lines = [
        "% Auto-generated by paper_tabs_figs/tab_abl_refM.py -- do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        f"\\caption{{Effect of the reference budget $M$ on CIFAR10 with"
        f" $q={q_pct}\\%$. Precision@$k$ retrieves"
        f" $\\lceil k\\cdot n_{{\\mathrm{{mem}}}}/100\\rceil$ members and is not"
        f" truncated at $|V|$.}}",
        "\\label{tab:abl-refM}",
        "\\setlength{\\tabcolsep}{6pt}",
        "\\renewcommand{\\arraystretch}{1.05}",
        "\\resizebox{\\columnwidth}{!}{%",
        "\\begin{tabular}{lccc}",
        "\\toprule",
        "\\textbf{$M$} & \\textbf{P@1\\%} & \\textbf{P@3\\%}"
        " & \\textbf{P@5\\%} \\\\",
        "\\midrule",
    ]
    for mi, m in enumerate(M_LIST):
        cells = [f"$M={m}$"]
        for j in range(len(K_FRACS)):
            body = f"{cell_mean[mi, j]:.3f} \\pm {cell_std[mi, j]:.3f}"
            deco = col_deco[j].get(mi)
            if deco:
                body = f"\\{deco}{{{body}}}"
            cells.append(f"${body}$")
        lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]

    tex = "\n".join(lines)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(tex + "\n")
    print(tex)

    print("\n% ---- prose numbers ----")
    for j, k in enumerate(["P@1%", "P@3%", "P@5%"]):
        d12 = (cell_mean[1, j] - cell_mean[0, j]) * 100
        d18 = (cell_mean[3, j] - cell_mean[0, j]) * 100
        print(f"% {k}: M=1 {cell_mean[0, j]:.3f}; M=2 delta {d12:+.2f} pp; "
              f"M=8 delta vs M=1 {d18:+.2f} pp")


if __name__ == "__main__":
    main()
