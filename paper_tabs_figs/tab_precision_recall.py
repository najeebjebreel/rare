"""Generate the appendix Precision/Recall@k LaTeX table (tab:precision-recall).

Every method of the main results table, at k in {1,3,5,10}%, under LiRA-256
gold at FPR<=1e-4, on all three WRN-28-2 benchmarks. One panel per dataset,
mean +/- std over the 10 targets.

Structure follows Pollock et al. Tables 10-11: Precision@k and Recall@k side
by side over a shared depth grid, with the gold-set geometry stated once per
panel rather than repeated per row.

    Precision@k = |M_k n V| / m_k          m_k = ceil(k% * n_mem)
    Recall@k    = |M_k n V| / |V|
    max Recall@k = min(m_k, |V|) / |V|     -- the ceiling any ranker faces

The per-panel header block reports n_mem, |V|, m_k and that ceiling: all are
method-independent, so recall must be read against the ceiling rather than
against 1 wherever m_k < |V|.

Outputs: tables/tab_precision_recall.{csv,tex}. CPU-only; nothing retrained.

Usage:
  python paper_tabs_figs/tab_precision_recall.py
"""

from __future__ import annotations

import argparse
import csv as _csv
import math
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
for p in (str(ROOT), str(ROOT / "scripts")):
    if p not in sys.path:
        sys.path.insert(0, p)

from paper_tabs_figs._tex import ADJUSTBOX_OPEN, column_marks, pm_scriptsize  # noqa: E402

import paper_tabs_figs._scores as _mt  # noqa: E402

BENCHMARKS = {
    "CIFAR10": ROOT / "experiments/cifar10/wrn28-2/2025-12-07_0140",
    "CIFAR100": ROOT / "experiments/cifar100/wrn28-2/2025-12-25_0121",
    "CINIC10": ROOT / "experiments/cinic10/wrn28-2/2026-05-11_0215",
}
DEFAULT_TARGETS = [0, 25, 50, 75, 100, 125, 150, 175, 200, 250]
DEFAULT_OUTPUT = ROOT / "paper_tabs_figs/tables/tab_precision_recall.tex"
K_FRACS = [0.01, 0.03, 0.05, 0.10]
FPR = 1e-4

# Same rows, same order, as paper_tabs_figs/tab_main.py.
METHODS = [
    ("LiRA (M=8)", lambda e, t: _mt.load_attack_scores(e, t, "LiRA", 8)),
    ("RMIA (M=8)", lambda e, t: _mt.load_attack_scores(e, t, "RMIA", 8)),
    ("Attack-R (M=16)", lambda e, t: _mt.load_attack_scores(e, t, "Attack-R", 16)),
    ("LT-MLP (M=1)", lambda e, t: _mt.load_liu_mlp(e, t, 1)),
    ("LT-IQR (M=0)", lambda e, t: _mt.load_lt_iqr(e, t)),
    ("LOSS (M=0)", lambda e, t: _mt.load_loss_scores(e, t)),
    ("\\rare{} (M=1)", lambda e, t: _mt.load_rare(e, t, 1)),
]
GROUP_BREAKS = {"LT-IQR (M=0)", "\\rare{} (M=1)"}


def panel(exp: Path, targets):
    """(precision, recall, geometry) for one dataset.

    precision/recall: {label: (mean, std) arrays of len(K_FRACS)}
    geometry: dict of the method-independent header quantities.
    """
    n_mem, n_v, budgets, max_rec = [], [], [], []
    for t in targets:
        gold, members, vulnerable = _mt.load_lira_gold(exp, t, FPR)
        ok = members & np.isfinite(gold)
        nm, nv = int(ok.sum()), int(vulnerable[ok].sum())
        n_mem.append(nm); n_v.append(nv)
        b = [math.ceil(k * nm) for k in K_FRACS]
        budgets.append(b)
        max_rec.append([min(bi, nv) / nv for bi in b])

    prec, rec = {}, {}
    for label, loader in METHODS:
        P, R = [], []
        for t in targets:
            gold, members, vulnerable = _mt.load_lira_gold(exp, t, FPR)
            pr = _mt.tail_metrics_at_k(
                loader(exp, t), members, K_FRACS,
                vulnerable=vulnerable, gold_scores=gold)
            P.append([float(pr.iloc[i]["precision"]) for i in range(len(K_FRACS))])
            R.append([float(pr.iloc[i]["recall"]) for i in range(len(K_FRACS))])
        P, R = np.asarray(P), np.asarray(R)
        prec[label] = (P.mean(0), P.std(0, ddof=1))
        rec[label] = (R.mean(0), R.std(0, ddof=1))

    geom = dict(
        n_mem=float(np.mean(n_mem)),
        n_v_mean=float(np.mean(n_v)), n_v_std=float(np.std(n_v, ddof=1)),
        budget=np.asarray(budgets, dtype=float).mean(0),
        max_recall=np.asarray(max_rec, dtype=float).mean(0),
    )
    return prec, rec, geom


def _int(v: float) -> str:
    """Rounded integer with LaTeX thousands separators: 25054 -> 25{,}054."""
    return f"{v:,.0f}".replace(",", "{,}")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--targets", type=int, nargs="*", default=DEFAULT_TARGETS)
    ap.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = ap.parse_args()

    results = {n: panel(BENCHMARKS[n], args.targets) for n in BENCHMARKS}
    nk = len(K_FRACS)
    kdisp = [f"{int(k * 100)}\\%" for k in K_FRACS]

    lines = [
        "% Auto-generated by paper_tabs_figs/tab_precision_recall.py -- do not edit by hand.",
        r"""\begin{table}[t]
\centering
\caption{P@$k$\% and R@$k$\% under LiRA-256 gold at FPR$\leq10^{-4}$,
metrics as defined in Section~\ref{sec:eval-metrics}, mean$\pm$std over
10 targets. Each panel gives $n_{\mathrm{mem}}$, $|V|$ and $m_k$, and its
first row gives maxR@$k$\%, which is method-independent: where
$m_k<|V|$, recall cannot reach $1$ and must be read against that ceiling.
Bold denotes the best and underline the second best in each column;
ties after rounding receive the same formatting.}
\label{tab:precision-recall}
\setlength{\tabcolsep}{3pt}
\renewcommand{\arraystretch}{1.05}""",
        ADJUSTBOX_OPEN,
        "\\begin{tabular}{l cccc cccc}", "\\toprule",
        "\\multirow{2}{*}{\\textbf{Method}}"
        f" & \\multicolumn{{{nk}}}{{c}}{{\\textbf{{P@$k$\\%}}}}"
        f" & \\multicolumn{{{nk}}}{{c}}{{\\textbf{{R@$k$\\%}}}} \\\\",
        "\\cmidrule(lr){2-5} \\cmidrule(lr){6-9}",
        " " + " ".join(f"& \\textbf{{{k}}}" for k in kdisp)
        + " " + " ".join(f"& \\textbf{{{k}}}" for k in kdisp) + " \\\\",
    ]

    for name in BENCHMARKS:
        prec, rec, g = results[name]
        # Best / second per column within the panel, on displayed values.
        table = {lab: list(prec[lab][0]) + list(rec[lab][0]) for lab, _ in METHODS}
        marks = column_marks(table, 2)
        lines.append("\\midrule")
        lines.append(
            f"\\multicolumn{{9}}{{l}}{{\\textbf{{{name}}}\\quad"
            f" $n_{{\\mathrm{{mem}}}}={_int(g['n_mem'])}$,\\quad"
            f" $|V|={_int(g['n_v_mean'])}\\pm{g['n_v_std']:.0f}$,\\quad"
            f" $m_k={'/'.join(_int(b) for b in g['budget'])}$}} \\\\"
        )
        lines.append("\\cmidrule(lr){1-9}")
        lines.append("maxR@$k$\\% & " + " & ".join(["---"] * nk) + " & "
                     + " & ".join(f"{r:.2f}" for r in g["max_recall"]) + " \\\\")
        lines.append("\\cmidrule(lr){1-9}")
        for label, _ in METHODS:
            if label in GROUP_BREAKS:
                lines.append("\\midrule")
            vals = list(zip(prec[label][0], prec[label][1])) + list(zip(rec[label][0], rec[label][1]))
            cells = [label] + [pm_scriptsize(m, sd, 2, marks[label][j])
                               for j, (m, sd) in enumerate(vals)]
            lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n")

    with open(args.output.with_suffix(".csv"), "w", newline="") as f:
        w = _csv.writer(f)
        w.writerow(["dataset", "method", "k", "precision_mean", "precision_std",
                    "recall_mean", "recall_std", "n_mem", "gold_size",
                    "budget", "max_recall"])
        for name in BENCHMARKS:
            prec, rec, g = results[name]
            for label, _ in METHODS:
                for j, k in enumerate(K_FRACS):
                    w.writerow([
                        name, label.replace("\\rare{}", "RARE"), f"{int(k*100)}%",
                        f"{prec[label][0][j]:.6f}", f"{prec[label][1][j]:.6f}",
                        f"{rec[label][0][j]:.6f}", f"{rec[label][1][j]:.6f}",
                        f"{g['n_mem']:.1f}", f"{g['n_v_mean']:.1f}",
                        f"{g['budget'][j]:.1f}", f"{g['max_recall'][j]:.4f}"])

    print("\n".join(lines))
    print(f"\n% wrote {args.output}")
    print(f"% wrote {args.output.with_suffix('.csv')}")


if __name__ == "__main__":
    main()
