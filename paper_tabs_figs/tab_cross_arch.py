"""Generate the cross-architecture generalization LaTeX table (tab:cross-arch).

CIFAR-10 only; the target backbone varies across ResNet-20, WRN-28-2, and
WRN-40-4. Every cell is Precision @ k in {1, 3, 5}% under that
architecture's own LiRA-256 gold (hits at the FPR threshold, intersected
with members), over a retrieval budget of ceil(k% * n_members); mean +/-
std over the 10 targets; the Avg column is the mean +/- std over the
three architecture means. Best per column is bold, second best
underlined.

Usage:
  python paper_tabs_figs/tab_cross_arch.py
  python paper_tabs_figs/tab_cross_arch.py --fpr 1e-3
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
for p in (str(ROOT), str(ROOT / "scripts")):
    if p not in sys.path:
        sys.path.insert(0, p)

_spec = importlib.util.spec_from_file_location(
    "main_table_mod", ROOT / "scripts" / "main_table.py")
_mt = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_mt)

BENCHMARKS = {
    "ResNet-20": ROOT / "experiments/cifar10/resnet20/2026-01-23_2258",
    "WRN-28-2": ROOT / "experiments/cifar10/wrn28-2/2025-12-07_0140",
    "WRN-40-4": ROOT / "experiments/cifar10/wrn40-4/2026-01-24_2029",
}
DEFAULT_TARGETS = [0, 25, 50, 75, 100, 125, 150, 175, 200, 250]
DEFAULT_OUTPUT = ROOT / "paper_tabs_figs/tables/tab_cross_arch.tex"
K_FRACS = [0.01, 0.03, 0.05]

METHODS = [
    ("LiRA ($M{=}8$)",
     lambda exp, t: _mt._load_attack_scores(exp, t, "LiRA", 8)),
    ("RMIA ($M{=}8$)",
     lambda exp, t: _mt._load_attack_scores(exp, t, "RMIA", 8)),
    ("Attack-R ($M{=}16$)",
     lambda exp, t: _mt._load_attack_scores(exp, t, "Attack-R", 16)),
    ("LT-MLP ($M{=}1$)",
     lambda exp, t: _mt._load_liu_mlp(exp, t, 1)),
    ("LT-IQR ($M{=}0$)",
     lambda exp, t: _mt._load_lt_iqr(exp, t)),
    ("LOSS ($M{=}0$)",
     lambda exp, t: _mt._load_loss_scores(exp, t)),
    ("\\rare{} ($M{=}1$)",
     lambda exp, t: _mt._load_rare(exp, t, 1)),
]
GROUP_BREAKS = {"\\rare{} ($M{=}1$)"}


def precision_at_k(exp: Path, targets, loader, fpr: float) -> np.ndarray:
    out = []
    for t in targets:
        gold_scores, members, vulnerable = _mt._load_lira_gold(exp, t, fpr)
        pr = _mt.tail_metrics_at_k(
            loader(exp, t), members, K_FRACS,
            vulnerable=vulnerable, gold_scores=gold_scores,
            cap_k_at_gold=False, k_rounding="ceil",
        )
        out.append([float(pr.iloc[i]["precision"]) for i in range(len(K_FRACS))])
    return np.asarray(out)


def _rank_decorations(col_means):
    order = np.argsort(-np.asarray(col_means))
    deco = {int(order[0]): "mathbf"}
    if len(order) > 1:
        deco[int(order[1])] = "underline"
    return deco


def _fmt(mean, std, deco):
    body = f"{mean:.2f}\\pm{std:.2f}"
    if deco:
        body = f"\\{deco}{{{body}}}"
    return f"${body}$"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--fpr", type=float, default=1e-4)
    ap.add_argument("--targets", type=int, nargs="*", default=DEFAULT_TARGETS)
    ap.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = ap.parse_args()

    arch_names = list(BENCHMARKS)
    n_cols = (len(arch_names) + 1) * len(K_FRACS)
    cell_mean = np.zeros((len(METHODS), n_cols))
    cell_std = np.zeros_like(cell_mean)
    for mi, (_, loader) in enumerate(METHODS):
        arch_means = []
        for ai, name in enumerate(arch_names):
            pk = precision_at_k(BENCHMARKS[name], args.targets, loader, args.fpr)
            cell_mean[mi, ai * 3:ai * 3 + 3] = pk.mean(axis=0)
            cell_std[mi, ai * 3:ai * 3 + 3] = pk.std(axis=0, ddof=1)
            arch_means.append(pk.mean(axis=0))
        arch_means = np.asarray(arch_means)
        cell_mean[mi, -3:] = arch_means.mean(axis=0)
        cell_std[mi, -3:] = arch_means.std(axis=0, ddof=1)

    col_deco = [_rank_decorations(cell_mean[:, c]) for c in range(n_cols)]

    lines = [
        "% Auto-generated by paper_tabs_figs/tab_cross_arch.py -- do not edit by hand.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Cross-architecture generalization on CIFAR10 under LiRA-256"
        " gold. The target backbone varies across ResNet-20, WRN-28-2, and"
        " WRN-40-4. \\rare{} uses $M{=}1$ and $q=50\\%$.}",
        "\\label{tab:cross-arch}",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\renewcommand{\\arraystretch}{1.05}",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{lcccccccccccc}",
        "\\toprule",
        "\\textbf{Method}",
    ]
    for name in arch_names + ["Avg."]:
        lines.append(f"& \\multicolumn{{3}}{{c}}{{\\textbf{{{name}}}}}")
    lines += [
        "\\\\",
        "\\cmidrule(lr){2-4} \\cmidrule(lr){5-7} \\cmidrule(lr){8-10}"
        " \\cmidrule(lr){11-13}",
        " ".join("& \\textbf{P@1\\%} & \\textbf{P@3\\%} & \\textbf{P@5\\%}"
                 for _ in range(4)) + " \\\\",
        "\\midrule",
    ]
    for mi, (label, _) in enumerate(METHODS):
        if label in GROUP_BREAKS:
            lines.append("\\midrule")
        cells = [label]
        for c in range(n_cols):
            cells.append(_fmt(cell_mean[mi, c], cell_std[mi, c],
                              col_deco[c].get(mi)))
        lines.append("\n".join([
            cells[0],
            "& " + " & ".join(cells[1:4]),
            "& " + " & ".join(cells[4:7]),
            "& " + " & ".join(cells[7:10]),
            "& " + " & ".join(cells[10:13]) + " \\\\",
            "",
        ]))
    lines += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table*}"]

    tex = "\n".join(lines)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(tex + "\n")
    print(tex)

    ri = len(METHODS) - 1
    li = 0
    print("\n% ---- prose numbers ----")
    for j, k in enumerate(["P@1%", "P@3%", "P@5%"]):
        print(f"% Avg {k}: RARE {cell_mean[ri, -3 + j]:.2f}; "
              f"LiRA-8 {cell_mean[li, -3 + j]:.2f}")
        print(f"%   ResNet-20 {k}: RARE {cell_mean[ri, j]:.2f} vs LiRA-8 "
              f"{cell_mean[li, j]:.2f} (delta "
              f"{(cell_mean[ri, j] - cell_mean[li, j]) * 100:+.1f} pp)")


if __name__ == "__main__":
    main()
